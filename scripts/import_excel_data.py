                    shift_id = excluded.shift_id,
                    shift_code = excluded.shift_code,
                    shift_category = excluded.shift_category,
                    start_time = excluded.start_time,
                    end_time = excluded.end_time,
                    paid_hours = excluded.paid_hours,
                    generated = true
