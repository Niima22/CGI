def collect_employee_names(data_dir: Path) -> dict[str, dict[str, str]]:
    employees: dict[str, dict[str, str]] = {}
    for filename in ["planning 1.xlsx", "KPI - DS Magasin (1) (1).xlsx", "tickets.xlsx"]:
        path = data_dir / filename
        if not path.exists():
            continue
        workbook = openpyxl.load_workbook(path, read_only=True, data_only=True)
        try:
            for sheet in workbook.worksheets:
                for row in sheet.iter_rows(values_only=True):
                    name = extract_agent_name(row)
                    if not name:
                        continue
                    normalized = normalize_name(name)
                    department = department_from_sheet(sheet.title)
                    employees.setdefault(normalized, {"full_name": name, "department": department, "bannette": department})
        finally:
            workbook.close()
    return employees


def extract_agent_name(row: Iterable[Any]) -> str | None:
    values = list(row)
    shift_indexes = [idx for idx, value in enumerate(values) if parse_shift(value)]
    if shift_indexes:
        first_shift = shift_indexes[0]
        for value in reversed(values[max(0, first_shift - 6):first_shift]):
            text = clean_text(value)
            if looks_like_person_name(text):
                return title_name(text)

    for value in values[:4]:
        text = clean_text(value)
        if looks_like_person_name(text):
            return title_name(text)
    return None


def looks_like_person_name(text: str) -> bool:
    if not text or len(text) < 5 or len(text) > 80:
        return False
    if parse_shift(text) or text.upper() in {"OFF", "BO", "FO", "SCO", "AGENT", "BANNETTES"}:
        return False
    if any(ch.isdigit() for ch in text):
        return False
    parts = [part for part in re.split(r"\s+", text.strip()) if part]
    return len(parts) >= 2 and all(len(part) > 1 for part in parts[:2])


def title_name(text: str) -> str:
    return " ".join(part.capitalize() if part.isupper() else part for part in text.split())


def department_from_sheet(sheet_name: str) -> str:
    upper = sheet_name.upper()
    if "BO" in upper:
        return "Back Office"
    if "FO" in upper:
        return "Front Office"
    if "SUP" in upper:
        return "Supervision"
    return "Support"


def import_employees(conn, employees: dict[str, dict[str, str]]) -> None:
    if not employees:
        return
    with conn.cursor() as cursor:
        departments = sorted({item["department"] for item in employees.values()})
        execute_values(
            cursor,
            """
            insert into departments (name, description, active, created_at, updated_at)
            values %s
            on conflict (name) do update set updated_at = excluded.updated_at, active = true
            """,
            [(dept, f"Département importé depuis les fichiers Excel.", True, datetime.now(), datetime.now()) for dept in departments],
        )

        rows = []
        for index, item in enumerate(sorted(employees.values(), key=lambda value: value["full_name"])):
            availability = ["AVAILABLE", "IN_COMMUNICATION", "BREAK", "LEAVE", "OFFLINE"][index % 5]
            rows.append(
                (
                    item["full_name"],
                    item["department"],
                    item["bannette"],
                    "Import Excel",
                    "Actif",
                    "ACTIVE",
                    availability,
                    datetime.now(),
                    datetime.now(),
                )
            )
        for row in rows:
            cursor.execute(
                """
                update employees
                set department = %s,
                    bannette = %s,
                    operational_status = %s,
                    activity_status = %s,
                    account_status = %s,
                    availability_status = %s,
                    updated_at = now()
                where lower(full_name) = lower(%s)
                """,
                (row[1], row[2], row[3], row[4], row[5], row[6], row[0]),
            )
            if cursor.rowcount == 0:
                cursor.execute(
                    """
                    insert into employees (
                        full_name, department, bannette, operational_status, activity_status,
                        account_status, availability_status, created_at, updated_at
                    )
                    values (%s, %s, %s, %s, %s, %s, %s, %s, %s)
                    """,
                    row,
                )
    print(f"Imported/updated employees: {len(employees)}")


