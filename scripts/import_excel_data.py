@dataclass(frozen=True)
class DbConfig:
    host: str
    port: int
    user: str
    password: str


def main() -> int:
    parser = argparse.ArgumentParser(description="Import CGI-Intranet Excel data into local PostgreSQL.")
    parser.add_argument("--data-dir", required=True)
    parser.add_argument("--host", required=True)
    parser.add_argument("--port", required=True, type=int)
    parser.add_argument("--user", required=True)
    parser.add_argument("--password", required=True)
    parser.add_argument("--auth-db", required=True)
    parser.add_argument("--ticket-db", required=True)
    parser.add_argument("--employee-db", required=True)
    parser.add_argument("--planning-db", required=True)
    args = parser.parse_args()

    data_dir = Path(args.data_dir)
    if not data_dir.exists():
        raise SystemExit(f"Data directory not found: {data_dir}")

    config = DbConfig(args.host, args.port, args.user, args.password)

    ensure_database(config, args.auth_db)
    ensure_database(config, args.ticket_db)
    ensure_database(config, args.employee_db)
    ensure_database(config, args.planning_db)

    with connect(config, args.ticket_db) as ticket_conn, connect(config, args.employee_db) as employee_conn, connect(config, args.planning_db) as planning_conn:
        ensure_ticket_schema(ticket_conn)
        ensure_employee_schema(employee_conn)
        ensure_planning_schema(planning_conn)

        user_ids = read_auth_user_ids(config, args.auth_db)
        employees = collect_employee_names(data_dir)
        import_employees(employee_conn, employees)
        import_planning(planning_conn, employees, data_dir)
        ticket_refs = import_tickets(ticket_conn, data_dir, user_ids)
        import_ticket_reporting(ticket_conn, data_dir)
        import_kpi_reporting(ticket_conn, data_dir)

        ticket_conn.commit()
        employee_conn.commit()
        planning_conn.commit()

    print("Excel import completed.")
    print(f"  employees/planning agents collected: {len(employees)}")
    print(f"  ticket references imported: {ticket_refs}")
    return 0


def connect(config: DbConfig, dbname: str):
    return psycopg2.connect(
        host=config.host,
        port=config.port,
        user=config.user,
        password=config.password,
        dbname=dbname,
    )


def ensure_database(config: DbConfig, dbname: str) -> None:
    conn = connect(config, "postgres")
    try:
        conn.autocommit = True
        with conn.cursor() as cursor:
            cursor.execute("select 1 from pg_database where datname = %s", (dbname,))
            if cursor.fetchone():
                return
            cursor.execute(f'create database "{dbname}"')
            print(f"Created database {dbname}")
    finally:
        conn.close()


def read_auth_user_ids(config: DbConfig, auth_db: str) -> dict[str, int]:
    ids = {"admin": 1, "manager": 2, "agent": 3}
    try:
        with connect(config, auth_db) as conn, conn.cursor() as cursor:
            cursor.execute(
                """
                select lower(email), id
                from user_profiles
                where lower(email) in ('pilote@cgi.local', 'superviseur@cgi.local', 'agent@cgi.local')
                """
            )
            for email, user_id in cursor.fetchall():
                if email == "pilote@cgi.local":
                    ids["admin"] = int(user_id)
                elif email == "superviseur@cgi.local":
                    ids["manager"] = int(user_id)
                elif email == "agent@cgi.local":
                    ids["agent"] = int(user_id)
    except Exception as exc:
        print(f"Auth user lookup skipped: {exc}")
    return ids


