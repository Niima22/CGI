        resolved_at = row[17]
        source = row[22]
        sla_status = map_sla_status(status, source)
        response_deadline = created_at + timedelta(minutes=15 if priority == "URGENT" else 60)
        resolution_deadline = created_at + timedelta(hours=4 if criticality == "CRITICAL" else 8)
        first_response_at = row[15] or (created_at + timedelta(minutes=10))
        consumed = 100.0 if sla_status == "BREACHED" else 85.0 if sla_status == "AT_RISK" else 40.0
