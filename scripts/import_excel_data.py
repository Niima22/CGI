def row_headers(row: Iterable[Any]) -> list[str]:
    headers = []
    seen = defaultdict(int)
    for index, value in enumerate(row):
        header = clean_text(value) or f"column_{index + 1}"
        seen[header] += 1
        if seen[header] > 1:
            header = f"{header}__{seen[header]}"
        headers.append(header)
    return headers


def map_ticket_status(value: Any, resolved_at: datetime | None, source_row: int) -> str:
    text = clean_text(value).upper()
    if resolved_at or "RESOL" in text or "CLOS" in text or "CLOT" in text:
        return "RESOLVED"
    if "ANNUL" in text or "CANCEL" in text:
        return "CANCELLED"
    return ACTIVE_STATUSES[source_row % len(ACTIVE_STATUSES)]


def map_priority(value: Any) -> str:
    text = clean_text(value).upper()
    if any(token in text for token in ["P1", "URG", "CRIT", "HAUTE", "HIGH"]):
        return "URGENT"
    if any(token in text for token in ["P2", "MOY", "MED"]):
        return "HIGH"
    if any(token in text for token in ["P3", "LOW", "BASSE", "FAIBLE"]):
        return "LOW"
    return "MEDIUM"


def map_criticality(priority: str, ttr_state: Any) -> str:
    text = clean_text(ttr_state).upper()
    if "DEP" in text or "KO" in text or priority == "URGENT":
        return "CRITICAL"
    if priority == "HIGH":
        return "HIGH"
    if priority == "LOW":
        return "LOW"
    return "MEDIUM"


def map_ticket_type(value: Any) -> str:
    text = clean_text(value).upper()
    if "CHANGE" in text:
        return "CHANGE"
    if "PROBLEM" in text or "PROBLEME" in text:
        return "PROBLEM"
    if "DEMANDE" in text or "REQUEST" in text:
        return "REQUEST"
    return "INCIDENT"


def map_sla_status(status: str, record: dict[str, Any]) -> str:
    ttr = clean_text(record.get("ETAT TTR")).upper()
    if "DEP" in ttr or "KO" in ttr:
        return "BREACHED"
    if status in {"NEW", "TODO", "ASSIGNED", "IN_PROGRESS"}:
        return "AT_RISK"
    if status in {"WAITING_PROVIDER", "WAITING_REQUESTER", "WAITING_MANAGER_VALIDATION"}:
        return "PAUSED"
    return "RESPECTED"


def reference_from_external_id(value: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "-", value.strip())
    return truncate(f"XLS-{cleaned}", 32)


def parse_shift(value: Any) -> tuple[str, time, time] | None:
    text = clean_text(value)
    if not text:
        return None
    if "OFF" == text.upper():
        return ("OFF", time(0, 0), time(0, 0))
    if "SCO" in text.upper() or "11H-20H" in text.upper():
        return ("SCO_11_20", time(11, 0), time(20, 0))
    match = SHIFT_RE.search(text)
    if not match:
        return None
    start_hour, start_minute, end_hour, end_minute = [int(part) for part in match.groups()]
    code = f"NORMAL_{start_hour:02d}_{end_hour:02d}"
    if start_hour == 3:
        code = "OPEN_03_12"
    elif start_hour == 5:
        code = "NORMAL_05_14"
    elif start_hour == 8:
        code = "NORMAL_08_17"
    elif start_hour == 9:
        code = "NORMAL_09_18"
    elif start_hour == 12:
        code = "CLOSE_12_21"
    elif start_hour == 13:
        code = "CLOSE_13_22"
    return (code, time(start_hour, start_minute), time(end_hour, end_minute))


def monday_of(value: date) -> date:
    return value - timedelta(days=value.weekday())


def clean_text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, datetime):
        return value.isoformat(sep=" ")
    text = str(value).replace("\n", " ").replace("\t", " ").strip()
    return re.sub(r"\s+", " ", text)


def normalize_name(value: str) -> str:
    return clean_text(value).casefold()


def truncate(value: str, max_length: int) -> str:
    return value[:max_length] if value else value


def slug(value: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9]+", "-", value.strip()).strip("-").upper()
    return truncate(cleaned or "UNKNOWN", 80)


def as_datetime(value: Any) -> datetime | None:
    if isinstance(value, datetime):
        return value.replace(tzinfo=None)
    if isinstance(value, date):
        return datetime.combine(value, time.min)
    text = clean_text(value)
    if not text:
        return None
    for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d", "%d/%m/%Y %H:%M:%S", "%d/%m/%Y"):
        try:
            return datetime.strptime(text, fmt)
        except ValueError:
            pass
    return None


def as_date(value: Any) -> date | None:
    parsed = as_datetime(value)
    return parsed.date() if parsed else None


def as_number(value: Any) -> float | None:
    if value is None or value == "":
        return None
    if isinstance(value, (int, float)):
        return float(value)
    text = clean_text(value).replace("%", "").replace(",", ".")
    try:
        return float(text)
    except ValueError:
        return None


def as_int(value: Any) -> int | None:
    number = as_number(value)
    return int(number) if number is not None else None


